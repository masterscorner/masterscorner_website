// Prints the SQL Better Auth needs for its tables, so it can be saved as a normal migration.
// Use: node scripts/gen-auth-sql.ts > db/migrations/0000_auth.sql (against an empty database).
import { Kysely } from 'kysely';
import { PostgresJSDialect } from 'kysely-postgres-js';
import postgres from 'postgres';
import { getMigrations } from 'better-auth/db/migration';
import { createAuth } from '../src/lib/server/auth-core.ts';

const url = process.env.DATABASE_URL ?? 'postgres://postgres@127.0.0.1:54329/postgres';
const sql = postgres(url, { max: 1, onnotice: () => {} });
const db = new Kysely<any>({ dialect: new PostgresJSDialect({ postgres: sql }) });
const auth = createAuth({ db, secret: 'x'.repeat(32), baseURL: 'http://localhost', sendOtp: async () => {} });
const { compileMigrations } = await getMigrations(auth.options, { throwOnUnsafe: false });
const out = await compileMigrations();
console.log('-- Better Auth tables (generated by scripts/gen-auth-sql.ts).\ncreate schema if not exists mc_auth;\n' + out);
await db.destroy();
