	<p>This notice explains, in simple words, what MastersCorner collects, why, and what you can do about it. It follows India's Digital Personal Data Protection Act, 2023 and its Rules.</p>

	<h2>Who we are</h2>
	<p>MastersCorner runs this website and app. For your account, public listings, reviews and search we decide how data is used. For a class's student records (attendance, fees, notes, grades) the class decides, and we keep the data for them.</p>

	<h2>What we collect and why</h2>
	<ul>
		<li><strong>Mobile number</strong>: to sign you in with a one-time code.</li>
		<li><strong>Name</strong>: so your classes know who you are.</li>
		<li><strong>Year of birth</strong>: to check you are an adult before you create an account or confirm a child.</li>
		<li><strong>Class records</strong> (attendance, batches, fees, levels): only when a class adds you, and only that class and you can see them.</li>
		<li><strong>Children's records</strong>: only after a parent or guardian confirms with their own verified mobile number.</li>
		<li><strong>Questions you send to a class</strong>: your name, phone and message go only to that class.</li>
		<li><strong>Reviews</strong>: your first name, star rating and comment are public.</li>
		<li><strong>Location</strong>: only when you tap "Near me" or "I am at my class now". We do not track you.</li>
	</ul>

	<h2>What we never do</h2>
	<ul>
		<li>We do not sell your data.</li>
		<li>We do not show advertising, and we never track or profile children.</li>
		<li>One class can never see another class's students, fees or notes.</li>
	</ul>

	<h2>Where your data is kept</h2>
	<p>Our database is in Mumbai, India. Pages are delivered through a global network (Cloudflare) so they load fast. Login codes are sent through an Indian SMS or WhatsApp provider.</p>

	<h2>Your rights</h2>
	<ul>
		<li>See a summary of your data, correct it, or delete it from Settings, or by writing to us.</li>
		<li>Withdraw consent at any time. Withdrawing is as easy as giving it.</li>
		<li>Name someone to act for you if you die or cannot act.</li>
		<li>Complain to our Grievance Officer. We answer within 90 days at most, usually much sooner. If you are not happy, you can complain to the Data Protection Board of India.</li>
	</ul>

	<h2>How long we keep data</h2>
	<p>As long as your account or class membership is active. If an account is inactive for a long time we tell you at least 48 hours before deleting it. A child's record that a parent does not confirm within 30 days is deleted automatically.</p>

